export const NARRATIVE_KEYS = NARRATIVE_SECTIONS.map((s) => s.key);

/**
 * Merge narrative changes without dropping unknown keys written by other
 * surfaces, and mirror thesis/free onto the legacy text columns.
 */
export function narrativePatch(entry: JournalEntry, patch: Narrative): EntryUpdate {
  const existingRaw = readJson<Record<string, unknown>>(entry, "narrative");
  const next = { ...existingRaw, ...readNarrative(entry), ...patch };
  const update: EntryUpdate = { narrative: next as unknown as EntryUpdate["narrative"] };
  if ("thesis" in patch) update.entry_reason_text = patch.thesis ?? null;
  if ("free" in patch) {
    update.notes_text = patch.free ?? null;
    update.word_count = (patch.free ?? "").trim().split(/\s+/).filter(Boolean).length;
  }
  return update;
}

