export type EntryOrigin = "manual" | "imported" | "synced" | "replay";

/** Where the row as a whole came from. Derived, never guessed at render time. */
export function entryOrigin(entry: JournalEntry): EntryOrigin {
  const sources = readJson<Record<string, FieldSource | string>>(entry, "field_sources");
  const declared = sources.__origin;
  if (declared === "imported" || declared === "replay" || declared === "synced" || declared === "manual") {
    return declared;
  }
  if (entry.trade_id) return "synced";
  return "manual";
}

export const ORIGIN_LABEL: Record<EntryOrigin, string> = {
  manual: "Manual",
  imported: "Imported",
  synced: "Broker synced",
  replay: "Replay",
};

/** Per-field origin, honouring stored overrides first. */
export function fieldSource(entry: JournalEntry, field: string): FieldSource {
  const stored = readJson<Record<string, FieldSource>>(entry, "field_sources")[field];
  if (stored) return stored;
  if ((CALCULATED_FIELDS as readonly string[]).includes(field)) return "calculated";
  const origin = entryOrigin(entry);
  if (origin !== "manual" && (EXECUTION_FACT_FIELDS as readonly string[]).includes(field)) {
    return origin === "imported" ? "imported" : origin === "replay" ? "replay" : "synced";
  }
  return "manual";
}

/**
 * Locked = upstream owns the value. Unlocking is explicit and recorded, so a
 * broker sync is never silently overwritten by a stray keystroke.
 */
export function isFieldLocked(entry: JournalEntry, field: string, correctionsUnlocked: boolean): boolean {
  if (correctionsUnlocked) return false;
  const src = fieldSource(entry, field);
  if (src === "corrected" || src === "manual") return false;
  if (src === "calculated") return true;
  return (EXECUTION_FACT_FIELDS as readonly string[]).includes(field);
}

/* ------------------------------------------------------------------ */
/* JSON payloads                                                       */
/* ------------------------------------------------------------------ */

export function readJson<T extends object>(entry: JournalEntry, key: string): T {
  const raw = (entry as unknown as Record<string, unknown>)[key];
  if (!raw || typeof raw !== "object" || Array.isArray(raw)) return {} as T;
  return raw as T;
}

