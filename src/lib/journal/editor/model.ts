export function computeDurationSeconds(
  open: string | null | undefined,
  close: string | null | undefined,
): number | null {
  if (!open || !close) return null;
  const s = Math.round((new Date(close).getTime() - new Date(open).getTime()) / 1000);
  return Number.isFinite(s) ? Math.max(0, s) : null;
}

/**
 * Structured plan/review values that have no dedicated column. They live in
 * the narrative jsonb under an `x` namespace so nothing new is migrated and
 * legacy readers (which only look at known narrative keys) stay unaffected.
 */
export type EditorExtras = {
  planned_entry?: number | null;
  risk_amount?: number | null;
  expected_rr?: number | null;
  invalidation?: string;
  management_plan?: string;
  entry_conditions?: string;
  exit_reason?: string;
  result?: string;
  timezone?: string;
  currency?: string;
  asset_class?: string;
  account_label?: string;
  broker_ref?: string;
  corrections_note?: string;
};

export function readExtras(entry: JournalEntry): EditorExtras {
  const nar = readJson<Record<string, unknown>>(entry, "narrative");
  const x = nar.x;
  if (!x || typeof x !== "object" || Array.isArray(x)) return {};
  return x as EditorExtras;
}

export function extrasPatch(entry: JournalEntry, patch: EditorExtras): EntryUpdate {
  const nar = readJson<Record<string, unknown>>(entry, "narrative");
  const next = { ...nar, x: { ...readExtras(entry), ...patch } };
  return { narrative: next as unknown as EntryUpdate["narrative"] };
}

